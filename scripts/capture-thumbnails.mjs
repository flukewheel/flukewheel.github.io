import { chromium } from '@playwright/test'
import { readdir, readFile, writeFile } from 'node:fs/promises'

const date = process.argv[2] ?? '2026-11-03'
const firstId = Number(process.argv[3] ?? 223)
const root = `supabase/catalogue/${date}`
const urls = (await readFile(`${root}-requested.txt`, 'utf8')).trim().split(/\r?\n/)
const output = 'apps/web/public/thumbnails'
const browser = await chromium.launch({ headless: true })
const outcomes = []
let next = 0

async function worker() {
  while (next < urls.length) {
    const index = next++
    const url = urls[index]
    const id = `20000000-0000-4000-8000-${String(firstId + index).padStart(12, '0')}`
    const page = await browser.newPage({ viewport: { width: 960, height: 540 }, ignoreHTTPSErrors: true })
    try {
      const response = await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 12000 })
      if (!response || response.status() >= 400) throw new Error(`HTTP ${response?.status() ?? 'unknown'}`)
      await page.waitForTimeout(900)
      await page.screenshot({ path: `${output}/${id}.jpg`, type: 'jpeg', quality: 64, animations: 'disabled' })
      outcomes[index] = { id, url, status: 'captured' }
    } catch (error) {
      outcomes[index] = { id, url, status: 'placeholder', reason: error instanceof Error ? error.message : String(error) }
    } finally {
      await page.close()
    }
  }
}

await Promise.all(Array.from({ length: 6 }, () => worker()))
await browser.close()
const ids = (await readdir(output)).filter((name) => /^20000000-0000-4000-8000-[0-9]{12}\.jpg$/.test(name)).map((name) => name.slice(0, -4)).sort()
await writeFile('apps/web/src/lib/thumbnailIds.ts', `// Generated by scripts/capture-thumbnails.mjs.\nexport const thumbnailIds = new Set([\n${ids.map((id) => `  "${id}",`).join('\n')}\n])\n`)
await writeFile(`${root}-thumbnail-results.json`, JSON.stringify(outcomes, null, 2))
console.log(JSON.stringify({ total: outcomes.length, captured: outcomes.filter((item) => item.status === 'captured').length, placeholders: outcomes.filter((item) => item.status === 'placeholder').length }))
