import { chromium } from '@playwright/test'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const webRoot = fileURLToPath(new URL('..', import.meta.url))
const outputDir = path.join(webRoot, 'public', 'thumbnails')
const env = await readFile(path.join(webRoot, '.env.local'), 'utf8')
const settings = Object.fromEntries(
  env.split(/\r?\n/).filter((line) => line && !line.startsWith('#'))
    .map((line) => {
      const separator = line.indexOf('=')
      return [line.slice(0, separator), line.slice(separator + 1)]
    }),
)
const apiUrl = settings.VITE_SUPABASE_URL
const publishableKey = settings.VITE_SUPABASE_PUBLISHABLE_KEY
if (!apiUrl || !publishableKey) throw new Error('Local Supabase configuration is missing.')

const response = await fetch(
  `${apiUrl}/rest/v1/websites?select=id,original_url&order=approved_at.desc&limit=1000`,
  { headers: { apikey: publishableKey, Authorization: `Bearer ${publishableKey}` } },
)
if (!response.ok) throw new Error(`Catalogue request failed: ${response.status}`)
const websites = await response.json()
await mkdir(outputDir, { recursive: true })
const existingIds = new Set((await readdir(outputDir)).filter((name) => name.endsWith('.jpg')).map((name) => name.slice(0, -4)))
const requestedIds = new Set(process.argv.slice(2))
const pendingWebsites = websites.filter((website) => !existingIds.has(website.id) && (requestedIds.size === 0 || requestedIds.has(website.id)))

const browser = await chromium.launch({ headless: true })
let next = 0
const results = []
async function capture() {
  while (next < pendingWebsites.length) {
    const website = pendingWebsites[next++]
    const context = await browser.newContext({
      viewport: { width: 960, height: 540 },
      deviceScaleFactor: 1,
      ignoreHTTPSErrors: true,
    })
    const page = await context.newPage()
    await page.route(/\.(woff2?|ttf|otf)(\?|$)/i, (route) => route.abort())
    try {
      const visit = await page.goto(website.original_url, {
        waitUntil: 'commit',
        timeout: 25_000,
      })
      if (!visit || visit.status() >= 400) {
        throw new Error(`HTTP ${visit?.status() ?? 'navigation failed'}`)
      }
      await page.waitForTimeout(1600)
      const thumbnail = path.join(outputDir, `${website.id}.jpg`)
      try {
        await page.screenshot({ path: thumbnail, type: 'jpeg', quality: 62, timeout: 20_000, animations: 'disabled' })
      } catch {
        const devtools = await context.newCDPSession(page)
        const capture = await devtools.send('Page.captureScreenshot', { format: 'jpeg', quality: 62, captureBeyondViewport: false })
        await writeFile(thumbnail, Buffer.from(capture.data, 'base64'))
      }
      results.push({ id: website.id, status: 'captured' })
    } catch (error) {
      results.push({ id: website.id, status: 'failed', reason: String(error).slice(0, 140) })
    } finally {
      await context.close()
    }
  }
}

try {
  await Promise.all(Array.from({ length: 4 }, capture))
} finally {
  await browser.close()
}
const capturedIds = (await readdir(outputDir)).filter((name) => name.endsWith('.jpg')).map((name) => name.slice(0, -4)).sort()
await writeFile(
  path.join(webRoot, 'src', 'lib', 'thumbnailIds.ts'),
  `// Generated by scripts/capture-thumbnails.mjs.\nexport const thumbnailIds = new Set(${JSON.stringify(capturedIds, null, 2)})\n`,
)
console.log(`Captured ${capturedIds.length}/${websites.length} webpage thumbnails.`)
for (const result of results.filter((item) => item.status === 'failed')) {
  console.log(`Failed ${result.id}: ${result.reason}`)
}
