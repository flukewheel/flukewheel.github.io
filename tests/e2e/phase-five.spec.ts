import { expect, test } from '@playwright/test'
import { showMobileMenu } from './mobileMenu'

test('guests browse bounded recent cards and paged categories without a viewer on home', async ({ page }) => {
  const externalFrameRequests: string[] = []
  page.on('request', (request) => {
    if (request.isNavigationRequest() && request.frame().parentFrame()) externalFrameRequests.push(request.url())
  })

  await page.goto('/#/')
  await expect(page.getByRole('region', { name: 'For you' }).getByRole('button', { name: 'Log in / Sign up' })).toBeVisible()
  await expect(page.locator('.card-carousel .website-card')).toHaveCount(10)
  expect(externalFrameRequests).toEqual([])
  await expect(page.locator('iframe')).toHaveCount(0)

  await page.getByRole('link', { name: 'See all websites' }).click()
  await expect(page).toHaveURL(/#\/recent$/)
  await expect(page.locator('.browse-page .website-card')).toHaveCount(24)
  await page.getByRole('button', { name: 'Show more websites' }).click()
  await expect(page.locator('.browse-page .website-card')).toHaveCount(48)

  await showMobileMenu(page)
  await page.getByRole('button', { name: 'Discovery interest' }).click()
  await page.getByRole('button', { name: 'Arts, Design & Crafts' }).click()
  await expect(page).toHaveURL(/#\/category\/[0-9a-f-]{36}$/i)
  await expect(page.locator('.browse-page .website-card').first()).toBeVisible()
  const categories = await page.locator('.browse-page .website-card__meta span:last-child').allTextContents()
  expect(categories.every((text) => text.includes('Art'))).toBe(true)
  await page.getByRole('link', { name: 'Clear category' }).click()
  await expect(page).toHaveURL(/#\/recent$/)
  await showMobileMenu(page)
  await expect(page.getByRole('button', { name: 'Discovery interest' })).toContainText('All interests')
})

test('returning from a category restores the homepage position', async ({ page }) => {
  await page.goto('/#/')
  await expect(page.locator('.category-card')).toHaveCount(6)
  const seeMore = page.getByRole('button', { name: 'See more' })
  await expect(seeMore).toHaveAttribute('aria-expanded', 'false')
  await seeMore.click()
  await expect(page.locator('.category-card')).toHaveCount(20)
  const accents = await page.locator('.category-card').evaluateAll((cards) => cards.map((card) => getComputedStyle(card).getPropertyValue('--category-accent').trim()))
  expect(new Set(accents).size).toBe(20)
  expect(accents).toEqual(Array.from({ length: 20 }, (_, index) => `hsl(${(28 + index * 18) % 360} 80% 66%)`))
  await page.getByRole('button', { name: 'See less' }).click()
  await expect(page.locator('.category-card')).toHaveCount(6)
  await expect(seeMore).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('heading', { name: 'Explore categories' }).scrollIntoViewIfNeeded()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(200)
  const homePosition = await page.evaluate(() => window.scrollY)
  await page.getByRole('link', { name: /Arts, Design & Crafts Art, illustration/ }).click()
  await expect(page).toHaveURL(/#\/category\/[0-9a-f-]{36}$/i)
  await page.getByRole('link', { name: /Back to homepage/ }).click()
  await expect(page).toHaveURL(/#\/$/)
  await expect.poll(() => page.evaluate((previous) => Math.abs(window.scrollY - previous), homePosition)).toBeLessThan(200)
})

test('members receive cold-start recommendations and guests see the prompt after logout', async ({ page }) => {
  const email = `phase5-${crypto.randomUUID()}@example.test`
  await page.goto('/#/')
  await showMobileMenu(page)
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await page.getByRole('button', { name: 'Create an account' }).click()
  await page.getByRole('textbox', { name: 'Email address' }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('FlukewheelTestPassword42!')
  const rpcResponse = page.waitForResponse((response) => response.url().includes('/rpc/recommend_website_ids'))
  await page.getByRole('button', { name: 'Sign up', exact: true }).click()
  expect((await rpcResponse).status()).toBe(200)
  await expect(page.getByRole('heading', { name: 'Choose a username' })).toBeVisible()
  await page.getByRole('button', { name: 'Not now' }).click()
  const accountTrigger = page.getByRole('button', { name: `Account menu for ${email.split('@')[0]}` })
  await showMobileMenu(page)
  await accountTrigger.click()
  const accountMenu = page.getByRole('menu')
  await expect(accountMenu.getByRole('menuitem')).toHaveCount(4)
  await expect(accountMenu.locator('.interest-option__icon svg')).toHaveCount(4)
  await expect(accountMenu.getByRole('menuitem', { name: 'Administration' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(accountMenu).toHaveCount(0)
  await expect(accountTrigger).toBeFocused()
  await page.goto('/#/viewer/20000000-0000-4000-8000-000000000115')
  await page.locator('.viewer-shell iframe').waitFor()
  await showMobileMenu(page)
  await accountTrigger.click()
  await expect(accountMenu).toBeVisible()
  await page.mouse.click(10, 100)
  await expect(accountMenu).toHaveCount(0)
  await page.goto('/#/')
  const forYou = page.getByRole('region', { name: 'For you' })
  await expect(forYou.locator('.website-card')).toHaveCount(6)
  const recommendedCard = forYou.locator('.website-card').first()
  const recentCard = page.getByRole('region', { name: 'Recently added' }).locator('.website-card').first()
  await expect(recommendedCard).toHaveClass(/website-card--image-overlay/)
  await expect(recommendedCard.locator('.website-card__meta')).toHaveCount(0)
  await expect(recommendedCard.getByRole('button', { name: /Take a look at/ })).toBeVisible()
  expect(await recommendedCard.locator('.website-card__body').evaluate((body) => [...body.children].map((child) => child.tagName))).toEqual(['H3', 'P', 'BUTTON'])
  expect(await recommendedCard.evaluate((card) => getComputedStyle(card).fontFamily)).toContain('Space Mono Local')
  expect((await recommendedCard.boundingBox())!.height).toBe((await recentCard.boundingBox())!.height)
  expect(Math.abs((await recommendedCard.locator('.website-card__art').boundingBox())!.height - (await recommendedCard.boundingBox())!.height)).toBeLessThanOrEqual(2)
  await expect(forYou.getByRole('link', { name: 'Choose interests' })).toBeVisible()
  await expect(page.locator('iframe')).toHaveCount(0)

  await forYou.getByRole('link', { name: 'Choose interests' }).click()
  await expect(page.getByRole('heading', { name: 'Profile and interests' })).toBeVisible()
  await page.getByRole('checkbox', { name: /Arts, Design & Crafts/ }).check()
  await expect(page.getByRole('checkbox', { name: /Arts, Design & Crafts/ })).toBeChecked()
  const refreshedRecommendations = page.waitForResponse((response) => response.url().includes('/rpc/recommend_website_ids'))
  await page.getByRole('link', { name: /Back to discovery/ }).click()
  expect((await refreshedRecommendations).status()).toBe(200)
  await expect(forYou.locator('.website-card')).toHaveCount(6)

  await showMobileMenu(page)
  await page.getByRole('button', { name: 'Discovery interest' }).click()
  await page.getByRole('button', { name: 'Arts, Design & Crafts' }).click()
  await expect(page).toHaveURL(/#\/category\/[0-9a-f-]{36}$/i)
  await page.getByRole('link', { name: /Back to homepage/ }).click()
  await expect(forYou.locator('.website-card')).toHaveCount(6)
  await expect(forYou.locator('.website-card__meta')).toHaveCount(0)

  const secondTab = await page.context().newPage()
  await secondTab.goto('/#/')
  await expect(secondTab.getByRole('region', { name: 'For you' }).locator('.website-card')).toHaveCount(6)
  await showMobileMenu(page)
  await page.getByRole('button', { name: `Account menu for ${email.split('@')[0]}` }).click()
  await page.getByRole('menuitem', { name: 'Log out' }).click()
  await page.goto('/#/')
  await expect(forYou.getByRole('button', { name: 'Log in / Sign up' })).toBeVisible()
  await expect(forYou.locator('.website-card')).toHaveCount(0)
  await expect(secondTab.getByRole('region', { name: 'For you' }).getByRole('button', { name: 'Log in / Sign up' })).toBeVisible()
  await secondTab.close()
})

test('members can retry a recommendation failure without losing the home feed', async ({ page }) => {
  const email = `phase5-retry-${crypto.randomUUID()}@example.test`
  await page.route('**/rpc/recommend_website_ids', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Temporary failure"}' }))
  await page.goto('/#/')
  await showMobileMenu(page)
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await page.getByRole('button', { name: 'Create an account' }).click()
  await page.getByRole('textbox', { name: 'Email address' }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('FlukewheelTestPassword42!')
  await page.getByRole('button', { name: 'Sign up', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Choose a username' })).toBeVisible()
  await page.getByRole('button', { name: 'Not now' }).click()
  const forYou = page.getByRole('region', { name: 'For you' })
  await expect(forYou.getByText('Your recommendations could not be loaded.')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Recently added' }).locator('.website-card')).toHaveCount(10)
  await page.unroute('**/rpc/recommend_website_ids')
  await forYou.getByRole('button', { name: 'Try again' }).click()
  await expect(forYou.locator('.website-card')).toHaveCount(6)
})
